def slug(text):
    text = re.sub(r"<[^>]+>", "", text).lower()
    return re.sub(r"[^\w\- ]", "", text, flags=re.UNICODE).strip().replace(" ", "-")


def site_path(relative):
    """Path inside a language tree for a repository-relative Markdown file, or None when it is not a site page."""
    if relative in HOME.values():
        return "index.html"
    command = re.fullmatch(r"docs/commands/([\w-]+?)(\.es)?\.md", relative)
    if command:
        return f"commands/{command.group(1)}.html"
    if relative.startswith("docs/") and relative.endswith(".md") and "/" not in relative[5:]:
        return relative[5:-3].removesuffix(".es") + ".html"
    return None


def link_target(href, source):
    """Rewrite a Markdown link from `source` (repository-relative) to a site URL relative to its page, or to GitHub."""
    if re.match(r"(https?:|mailto:|#)", href):
        return href
    path, _, anchor = href.partition("#")
    resolved = (ROOT / Path(source).parent / path).resolve()
    try:
        relative = resolved.relative_to(ROOT).as_posix()
    except ValueError:
        return href
    suffix = f"#{anchor}" if anchor else ""
    target = site_path(relative)
    if not target:
        return REPO + relative + suffix
    return posixpath.relpath(target, posixpath.dirname(site_path(source) or "")) + suffix


def inline(text, source):
    """Render code spans, bold and links; a link text may itself hold code spans."""
    token = re.compile(r"(`[^`]+`)|\[((?:[^\]`]|`[^`]+`)+)\]\(([^)\s]+)\)")
    out, position = [], 0

    def plain(part):
        return re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", html.escape(part, quote=False))

    for match in token.finditer(text):
        out.append(plain(text[position:match.start()]))
        if match.group(1):
            out.append(f"<code>{html.escape(match.group(1)[1:-1])}</code>")
        else:
            label = "".join(f"<code>{html.escape(piece[1:-1])}</code>" if piece.startswith("`") else plain(piece)
                            for piece in re.split(r"(`[^`]+`)", match.group(2)))
            out.append(f'<a href="{html.escape(link_target(match.group(3), source))}">{label}</a>')
        position = match.end()
    out.append(plain(text[position:]))
    return "".join(out)


def render(markdown, source):
    lines = markdown.split("\n")
    out, i, title = [], 0, None
    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            block = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            out.append(f"<pre><code>{html.escape(chr(10).join(block))}</code></pre>")
            i += 1
            continue
        heading = re.match(r"(#{1,6}) (.*)", line)
        if heading:
            level, text = len(heading.group(1)), inline(heading.group(2), source)
            title = title or re.sub(r"<[^>]+>", "", text)
            out.append(f'<h{level} id="{slug(text)}">{text}</h{level}>')
            i += 1
            continue
        if line.startswith("|") and i + 1 < len(lines) and re.match(r"\|[\s:|-]+\|?$", lines[i + 1]):
            cells = lambda row: [c.strip() for c in row.strip().strip("|").split("|")]  # noqa: E731
            head = "".join(f"<th>{inline(c, source)}</th>" for c in cells(line))
            rows, i = [], i + 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append("<tr>" + "".join(f"<td>{inline(c, source)}</td>" for c in cells(lines[i])) + "</tr>")
                i += 1
            out.append(f"<table><thead><tr>{head}</tr></thead><tbody>{''.join(rows)}</tbody></table>")
            continue
        item = re.match(r"(\s*)([-*]|\d+\.) (.*)", line)
        if item:
            ordered = item.group(2)[0].isdigit()
            entries = []
            while i < len(lines):
                current = re.match(r"(\s*)([-*]|\d+\.) (.*)", lines[i])
                if current:
                    entries.append(inline(current.group(3), source))
                elif lines[i].startswith("  ") and entries:
                    entries[-1] += " " + inline(lines[i].strip(), source)
                else:
                    break
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{e}</li>" for e in entries) + f"</{tag}>")
            continue
        if line.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].startswith(">"):
                quote.append(lines[i].lstrip("> "))
                i += 1
            out.append(f"<blockquote><p>{inline(' '.join(quote), source)}</p></blockquote>")
            continue
        if not line.strip():
            i += 1
            continue
        if re.match(r"</?(p|picture|source|img|a|div)\b", line):
            # A raw HTML block (the README banner, made for GitHub) is not part of the site: the header has the mark.
            while i < len(lines) and lines[i].strip():
                i += 1
            continue
        paragraph = []
        while i < len(lines) and lines[i].strip() and not re.match(r"(#{1,6} |```|\||>|\s*([-*]|\d+\.) )", lines[i]):
            paragraph.append(lines[i].strip())
            i += 1
        out.append(f"<p>{inline(' '.join(paragraph), source)}</p>")
    return "\n".join(out), title or source


def page(lang, catalog, name, body, title, pages, current, notice):
    url = "" if name == "index" else f"{name}.html"
    prefix = "../" * name.count("/")
    alternates = "".join(f'<link rel="alternate" hreflang="{other}" href="{BASE}{other}/{url}">' for other in LANGUAGES)
    alternates += f'<link rel="alternate" hreflang="x-default" href="{BASE}en/{url}">'
    other = "es" if lang == "en" else "en"
    nav = "".join(f'<li class="group">{html.escape(p_title)}</li>' if p_url is None else
                  f'<li data-url="{p_url}"><a href="{prefix}{p_url}"{" aria-current=page" if p_url == current else ""}>'
                  f"{html.escape(p_title)}</a></li>" for p_url, p_title in pages)
    banner = f'<p class="notice">{html.escape(notice)}</p>' if notice else ""
    return f"""<!doctype html>
<html lang="{lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title if title == 'DIXI Spec Kit' else title + ' · DIXI Spec Kit')}</title><link rel="canonical" href="{BASE}{lang}/{url}">{alternates}
<link rel="icon" type="image/svg+xml" href="{prefix}../assets/mark.svg"><style>{STYLE}</style></head><body>
<header><a class="brand" href="{prefix}index.html"><img src="{prefix}../assets/mark.svg" alt="" width="28" height="28">{html.escape(catalog["title"])}</a>
<span><a href="{prefix}../{other}/{url or 'index.html'}" hreflang="{other}">{html.escape(catalog["language"])}</a> ·
<a href="{REPO.replace('/blob/main/', '')}">{html.escape(catalog["source"])}</a></span></header>
<div class="layout"><nav aria-label="{html.escape(catalog["docs"])}">
<input id="search" type="search" placeholder="{html.escape(catalog["search"])}" aria-label="{html.escape(catalog["search"])}" hidden>
<ul id="pages">{nav}</ul></nav>
<main>{banner}{body}</main></div>{SEARCH.replace('__PREFIX__', prefix)}</body></html>
"""


def build(output):
    if output.exists():
        shutil.rmtree(output)
    docs = sorted(path for path in (ROOT / "docs").glob("*.md") if not path.name.endswith(".es.md"))

    def flat(doc, lang):
        """A document's Spanish version (`<name>.es.md`) is the page of the Spanish tree when it exists."""
        translated = f"docs/{doc.stem}.es.md"
        return translated if lang == "es" and (ROOT / translated).is_file() else f"docs/{doc.name}"

    for lang in LANGUAGES:
        catalog = json.loads((ROOT / "scripts/site" / f"{lang}.json").read_text(encoding="utf-8"))
        suffix = ".es.md" if lang == "es" else ".md"
        operations = sorted(path.name[:-len(suffix)] for path in (ROOT / "docs/commands").glob("*.md")
                            if path.name.endswith(".es.md") == (lang == "es"))
        operations.sort(key=lambda operation: operation != "index")
        commands = [(f"commands/{operation}", f"docs/commands/{operation}{suffix}") for operation in operations]
        sources = [("index", HOME[lang])] + [(doc.stem, flat(doc, lang)) for doc in docs] + commands
        rendered = {}
        for name, source in sources:
            rendered[name] = render((ROOT / source).read_text(encoding="utf-8"), source)
        pages = [("index.html" if n == "index" else f"{n}.html", catalog["home"] if n == "index" else rendered[n][1])
                 for n, _ in sources]
        pages.insert(len(pages) - len(commands), (None, catalog["commands"]))
        folder = output / lang
        (folder / "commands").mkdir(parents=True)
        index = []
        for name, source in sources:
            body, title = rendered[name]
            url = "index.html" if name == "index" else f"{name}.html"
            translated = name == "index" or "/" in name or source.endswith(".es.md")
            notice = "" if translated else catalog["english_only"]
            (folder / url).write_text(page(lang, catalog, name, body, title, pages, url, notice), encoding="utf-8")
            text = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", body)).strip()
            index.append({"url": url, "title": title, "text": text[:2000]})
        (folder / "search.json").write_text(json.dumps(index, ensure_ascii=False), encoding="utf-8")
    choose = "".join(f'<li><a href="{lang}/" hreflang="{lang}">{lang.upper()}</a></li>' for lang in LANGUAGES)
    (output / "index.html").write_text(f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>DIXI Spec Kit</title><link rel="canonical" href="{BASE}en/">
<link rel="alternate" hreflang="en" href="{BASE}en/"><link rel="alternate" hreflang="es" href="{BASE}es/">
<link rel="alternate" hreflang="x-default" href="{BASE}en/">
<script>var l=(navigator.language||'en').slice(0,2).toLowerCase();location.replace(l==='es'?'es/':'en/');</script>
</head><body><p>Choose a language · Elige un idioma</p><ul>{choose}</ul></body></html>
""", encoding="utf-8")
    (output / "assets").mkdir()
    shutil.copyfile(ROOT / "docs/assets/mark.svg", output / "assets/mark.svg")
    (output / ".nojekyll").write_text("", encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("usage: python3 scripts/build-site.py <output folder>", file=sys.stderr)
        sys.exit(2)
    build(Path(sys.argv[1]).resolve())
    print(f"Site built in {sys.argv[1]}")
